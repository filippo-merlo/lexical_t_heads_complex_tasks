"""E9 (scripts/e9_sets.py, e9_patch.sh): E8's DB set on the complex tasks; accuracies, answer checks,
set overlaps and the tables of paper/e9-complex-db.tex (no GPU, no statistical tests).

Accuracy of a condition = mean over the mean wordings (task: the seven rule wordings; control: the
control task's orig mean), at alpha 1 and at alpha 2 separately (no folds, so no cross-fitting).
References on the same items, means and replies: E2's rule-style J-head and Logit-head sets
(``results/patching_complex{,-wrong}.csv``), limited to alpha 1 and 2.

Answer checks, per condition and alpha, pooled over its mean wordings: share of replies with no
answer read by the flexible score, share of the most frequent answer (Yes/No and Tapatan labels),
and the constant-answer line (accuracy of giving every patched item the most frequent expected
label). Item overlap: per task wording, the items it gets right that the control also gets right.

Writes ``results/e9_complex_db/{accuracy,answers}.csv``, ``report.md`` and ``paper/tables/e9_*.tex``.

    .venv/bin/python scripts/e9_report.py
"""

from __future__ import annotations

import gzip
import json
import sys
from collections import Counter
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from e8_sets import N_HEADS  # noqa: E402

E9 = ROOT / "results" / "e9_complex_db"
E2 = ROOT / "results"
TABLES = ROOT / "paper" / "tables"
HEADER = "% Generated by scripts/e9_report.py; do not edit.\n"
ALPHAS = (1.0, 2.0)
CHECKS = {"complex": "check 1", "complex-wrong": "check 2"}
NAMES = {"noun_class_agreement/easy": "Noun Class Agreement", "lexical_category_inference/easy": "Lexical Category Inference",
         "set_game/easy": "Set Game", "operator_func/easy": "Operator Function", "tapatan/easy": "Tapatan"}
SETS = {"DB": "DB (E9)", "jhead": "J-head (E2)", "logithead": "Logit-head (E2)"}
LABELS = ("noun_class_agreement/easy", "lexical_category_inference/easy", "tapatan/easy")  # fixed label sets


def truth(x) -> bool:
    return x is True or str(x) == "True"


def no_answer(x) -> bool:
    return x is None or str(x) in ("", "None")


def load_e9() -> tuple[pd.DataFrame, list[dict]]:
    frames, lines = [], []
    for path in sorted(E9.glob("patching_complex*.csv")):
        frames.append(pd.read_csv(path))
        with gzip.open(E9 / "answers" / f"{path.stem}.jsonl.gz", "rt") as f:
            lines += [json.loads(line) for line in f]
    return pd.concat(frames, ignore_index=True), lines


def load_e2() -> tuple[pd.DataFrame, list[dict]]:
    frames, lines = [], []
    for family in CHECKS:
        c = pd.read_csv(E2 / f"patching_{family}.csv")
        frames.append(c[(c.source == "none") | (c.heads.isin(["jhead", "logithead"]) & c.alpha.isin(ALPHAS))])
        with gzip.open(E2 / "answers" / f"patching_{family}.jsonl.gz", "rt") as f:
            for line in f:
                x = json.loads(line)
                if x["source"] == "none" or (x["heads"] in ("jhead", "logithead") and float(x["alpha"]) in ALPHAS):
                    lines.append(x)
    return pd.concat(frames, ignore_index=True), lines


def summarise(c: pd.DataFrame) -> pd.DataFrame:
    rows = c[c.source != "none"]
    return (rows.groupby(["family", "task", "heads", "source", "alpha"], as_index=False)
            .agg(accuracy=("accuracy", "mean"), n_heads=("n_heads", "first"), n_wordings=("mean_wording", "nunique")))


def answer_checks(lines: list[dict]) -> pd.DataFrame:
    by = {}
    for x in lines:
        if x["source"] == "none":
            continue
        by.setdefault((x["family"], x["task"], x["heads"], x["source"], float(x["alpha"])), []).append(x)
    out = []
    for (family, task, heads, source, alpha), xs in sorted(by.items()):
        answered = [x for x in xs if not no_answer(x["predicted"])]
        top, n_top = Counter(str(x["predicted"]) for x in answered).most_common(1)[0] if answered else ("", 0)
        # One label: the accuracy of giving the answered replies' items the single label most
        # frequent among their references (the unanswered ones stay wrong), as a share of all.
        one = max(Counter(str(x["expected"]) for x in answered).values()) if answered else 0
        right = {}
        for x in xs:
            right.setdefault(x["mean_wording"], set())
            if truth(x["correct"]):
                right[x["mean_wording"]].add(x["item"])
        out.append(dict(family=family, task=task, heads=heads, source=source, alpha=alpha, n=len(xs),
                        answered=len(answered) / len(xs), no_answer=1 - len(answered) / len(xs),
                        accuracy=sum(truth(x["correct"]) for x in xs) / len(xs),
                        top_answer=top if task in LABELS else "",
                        top_share=n_top / len(xs) if task in LABELS else np.nan,
                        one_label=one / len(xs) if task in LABELS else np.nan,
                        right=json.dumps({w: sorted(s) for w, s in right.items()})))
    return pd.DataFrame(out)


def constant_line(lines: list[dict]) -> dict:
    """(family, task) -> accuracy of answering every patched item with the most frequent label."""
    out = {}
    for family in CHECKS:
        for task in LABELS:
            labels = Counter(str(x["expected"]) for x in lines if x["source"] == "none" and x["family"] == family
                             and x["task"] == task)
            if labels:
                out[family, task] = max(labels.values()) / sum(labels.values())
    return out


def overlap_with_control(a: pd.DataFrame) -> dict:
    """(family, task, heads, alpha) -> mean over task wordings of |right(w) & right(control)|,
    mean |right(w)|, |right(control)|."""
    out = {}
    for key, g in a.groupby(["family", "task", "heads", "alpha"]):
        task = g[g.source == "task"]
        control = g[g.source == "control"]
        if task.empty or control.empty:
            continue
        rt = list(json.loads(task.right.iloc[0]).values())
        rc = set(next(iter(json.loads(control.right.iloc[0]).values())))
        out[key] = (np.mean([len(set(r) & rc) for r in rt]), np.mean([len(r) for r in rt]), len(rc))
    return out


def generic_words(n: int = 50) -> set[str]:
    """The ``n`` words heads decode most on WikiText under J-head, E7's word rules (as
    ``scripts/e8_list_length.py``, which runs on import and is therefore not imported)."""
    import re

    from wordfreq import zipf_frequency

    from e8_sets import STOP, WORD
    from lth import DATA, READOUTS
    from lth.evaluation import tokenizer as get_tok

    assert WORD.pattern == re.compile(r"^[a-z]{3,}$").pattern
    tok, cache, counts = get_tok(), {}, Counter()

    def word(t: int):
        if t not in cache:
            w = tok.decode([t]).strip().lower()
            cache[t] = w if WORD.match(w) and w not in STOP and zipf_frequency(w, "en") >= 3 else None
        return cache[t]

    top = np.load(DATA / "readings" / "neutral" / "wikitext.npz")["top"][:, READOUTS.index("jhead")]
    for p in range(top.shape[0]):
        for h in range(top.shape[1]):
            counts.update({w for x in top[p, h] if (w := word(int(x)))})
    return set(sorted(counts, key=lambda w: (-counts[w], w))[:n])


