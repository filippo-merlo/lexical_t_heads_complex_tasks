def md(g: pd.DataFrame) -> str:
    """A DataFrame as a Markdown table, numbers to two decimals (no tabulate in the venv)."""
    def fmt(v):
        return "" if pd.isna(v) else f"{v:.2f}" if isinstance(v, (float, np.floating)) else str(v)
    g = g.reset_index()
    head = "| " + " | ".join(map(str, g.columns)) + " |"
    body = ["| " + " | ".join(fmt(v) for v in r) + " |" for r in g.itertuples(index=False)]
    return "\n".join([head, "|" + "---|" * len(g.columns), *body])


def cell(x, fmt="{:.2f}") -> str:
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "--"
    return fmt.format(x) if isinstance(x, (float, np.floating)) else str(x)


def write(name: str, align: str, header: list[str], rows: list[str]) -> None:
    TABLES.mkdir(parents=True, exist_ok=True)
    body = [HEADER + f"\\begin{{tabular}}{{{align}}}", "\\toprule", *header, "\\midrule", *rows, "\\bottomrule",
            "\\end{tabular}"]
    (TABLES / f"{name}.tex").write_text("\n".join(body) + "\n")


def table_lists(lists: dict, generic: set[str]) -> None:
    rows = []
    for task in NAMES:
        words = list(lists[task])
        shown = ", ".join(f"\\textit{{{w}}}" if w in generic else w for w in words)
        rows.append(f"{NAMES[task]} & {sum(w in generic for w in words)} & {shown} \\\\")
    write("e9_lists", "@{}p{2.6cm}cp{12.4cm}@{}", ["Task & Generic & Words (most active first; generic in italics) \\\\"], rows)


def table_sets(sizes: pd.DataFrame, db: dict, e2: dict) -> None:
    rows = []
    others = {t: set().union(*(db[u] for u in db if u != t)) for t in db}
    everywhere = set.intersection(*db.values())
    for task in NAMES:
        s, j, lg = db[task], e2[task]["jhead"], e2[task]["logithead"]
        r = sizes.set_index("task").loc[task]
        layers = sorted(h // N_HEADS for h in s)
        rows.append(" & ".join([NAMES[task], str(r.n_prompts), str(r.D), str(r.B), str(r.DB),
                                f"{layers[0]}--{layers[-1]} ({int(np.median(layers))})",
                                f"{len(s & j)}/{len(j)}", f"{len(s & lg)}/{len(lg)}",
                                str(len(s & others[task])), str(len(everywhere))]) + " \\\\")
    write("e9_sets", "@{}lrrrrcccrr@{}",
          ["Task & Prompts & D & B & DB & Layers (median) & in E2 J & in E2 L & in another DB & in all DB \\\\"], rows)


def table_check(family: str, s: pd.DataFrame, base: dict, const: dict) -> None:
    rows = []
    for task in NAMES:
        if (family, task) not in base:
            rows.append(f"{NAMES[task]} & \\multicolumn{{9}}{{l}}{{\\textit{{no item answered wrongly under orig}}}} \\\\")
            continue
        n, b = base[family, task]
        for k, (heads, label) in enumerate(SETS.items()):
            g = s[(s.family == family) & (s.task == task) & (s.heads == heads)].set_index(["source", "alpha"])
            if g.empty:
                continue
            cells = [cell(g.accuracy.get((src, a))) for src in ("task", "control") for a in ALPHAS]
            first = [NAMES[task], str(n), cell(b), cell(const.get((family, task)))] if k == 0 else ["", "", "", ""]
            rows.append(" & ".join([*first, label, str(int(g.n_heads.iloc[0])), *cells]) + " \\\\")
        rows.append("\\addlinespace")
    write(f"e9_{family.replace('-', '_')}", "@{}lrccl r cc cc@{}",
          [" & & & & & & \\multicolumn{2}{c}{Task mean} & \\multicolumn{2}{c}{Control mean} \\\\",
           "\\cmidrule(lr){7-8}\\cmidrule(lr){9-10}",
           "Task & Items & Unp. & Const. & Set & Heads & $\\alpha{=}1$ & $\\alpha{=}2$ & $\\alpha{=}1$ & $\\alpha{=}2$ \\\\"],
          rows[:-1])


def table_labels(a: pd.DataFrame) -> None:
    """The label tasks: share of replies with an answer, most frequent answer, accuracy, and the
    one-label line on the answered replies; DB and E2's J-head set, task and control means."""
    rows = []
    for family, check in CHECKS.items():
        first = True
        for task in LABELS:
            for heads in ("DB", "jhead"):
                g = a[(a.family == family) & (a.task == task) & (a.heads == heads)].set_index(["source", "alpha"])
                for source in ("task", "control"):
                    cells = []
                    for alpha in ALPHAS:
                        r = g.loc[(source, alpha)]
                        cells += [cell(r.answered), f"{r.top_answer} {r.top_share:.2f}" if r.top_share else "--",
                                  cell(r.accuracy), cell(r.one_label)]
                    rows.append(" & ".join([check if first else "", NAMES[task] if heads == "DB" and source == "task" else "",
                                            SETS[heads] if source == "task" else "", source, *cells]) + " \\\\")
                    first = False
            rows.append("\\addlinespace")
        rows[-1] = "\\midrule"
    write("e9_labels", "@{}llll cccc cccc@{}",
          [" & & & & \\multicolumn{4}{c}{$\\alpha{=}1$} & \\multicolumn{4}{c}{$\\alpha{=}2$} \\\\",
           "\\cmidrule(lr){5-8}\\cmidrule(lr){9-12}",
           "Check & Task & Set & Mean & Answered & Top answer & Right & One label & Answered & Top answer & Right & One label \\\\"],
          rows[:-1])


def table_overlap(overlap: dict) -> None:
    """Check 2: items right under a task mean (mean over the seven wordings), under the control
    mean, and under both (mean over wordings)."""
    rows = []
    for task in NAMES:
        for heads in ("DB", "jhead"):
            if ("complex-wrong", task, heads, 1.0) not in overlap:
                continue
            cells = []
            for alpha in ALPHAS:
                both, t, c = overlap["complex-wrong", task, heads, alpha]
                cells += [f"{t:.1f}", str(c), f"{both:.1f}"]
            rows.append(" & ".join([NAMES[task] if heads == "DB" else "", SETS[heads], *cells]) + " \\\\")
    write("e9_overlap", "@{}ll ccc ccc@{}",
          [" & & \\multicolumn{3}{c}{$\\alpha{=}1$} & \\multicolumn{3}{c}{$\\alpha{=}2$} \\\\",
           "\\cmidrule(lr){3-5}\\cmidrule(lr){6-8}",
           "Task & Set & Task mean & Control & Both & Task mean & Control & Both \\\\"], rows)


def table_wordings(c: pd.DataFrame) -> None:
    rows = []
    wordings = ["orig", *[f"w{i}" for i in range(1, 7)]]
    for family, check in CHECKS.items():
        for task in NAMES:
            g = c[(c.family == family) & (c.task == task) & (c.heads == "DB") & (c.source == "task")]
            if g.empty:
                continue
            for alpha in ALPHAS:
                v = g[g.alpha == alpha].set_index("mean_wording").accuracy
                rows.append(" & ".join([check if task == next(iter(NAMES)) and alpha == 1 else "",
                                        NAMES[task] if alpha == 1 else "", f"{alpha:g}",
                                        *[cell(v.get(w)) for w in wordings]]) + " \\\\")
        rows.append("\\midrule")
    write("e9_wordings", "@{}llc" + "c" * 7 + "@{}",
          ["Check & Task & $\\alpha$ & " + " & ".join(wordings) + " \\\\"], rows[:-1])


def main() -> None:
    c9, lines9 = load_e9()
    c2, lines2 = load_e2()
    base = {(r.family, r.task): (int(r.n_prompts), r.accuracy) for r in c9[c9.source == "none"].itertuples()}
    base2 = {(r.family, r.task): r.accuracy for r in c2[c2.source == "none"].itertuples()}
    assert all(abs(base2[k] - v[1]) < 1e-9 for k, v in base.items()), "E9 and E2 baselines differ"
    s = pd.concat([summarise(c9), summarise(c2)], ignore_index=True)
    s.to_csv(E9 / "accuracy.csv", index=False)
    a = pd.concat([answer_checks(lines9), answer_checks(lines2)], ignore_index=True)
    a.drop(columns="right").to_csv(E9 / "answers.csv", index=False)
    const = constant_line(lines9)
    overlap = overlap_with_control(a)

    # Sets and lists.
    db = {t: {l * N_HEADS + h for _, _, hs in v["sets"] for l, h in hs}
          for t, v in json.loads((E9 / "heads.json").read_text())["complex"].items()}
    heads2 = json.loads((E2 / "heads.json").read_text())["complex"]
    e2 = {t: {k: {l * N_HEADS + h for l, h, _ in heads2[t]["rule"][k]["heads"]} for k in ("jhead", "logithead")}
          for t in NAMES}
    lists = json.loads((E9 / "word_lists.json").read_text())["tasks"]
    table_lists(lists, generic_words())
    table_sets(pd.read_csv(E9 / "set_sizes.csv"), db, e2)
    for family in CHECKS:
        table_check(family, s, base, const)
    table_labels(a)
    table_overlap(overlap)
    table_wordings(c9)

    lines = ["# E9: E8's DB set on the complex tasks", "",
             "Accuracy = mean over mean wordings (task: 7 rule wordings; control: control task's orig mean), "
             "at alpha 1 and 2. References: E2's J-head and Logit-head rule sets on the same items, alpha 1 and 2.", ""]
    for family, check in CHECKS.items():
        g = s[s.family == family].pivot_table(index=["task", "heads"], columns=["source", "alpha"], values="accuracy")
        lines += [f"## {check} ({family})", "", "Baselines: " + ", ".join(
            f"{NAMES[t]} {base[family, t][1]:.2f} (n={base[family, t][0]})" for t in NAMES if (family, t) in base), "",
            md(g), ""]
    lines += ["## Answer checks", "", md(a.drop(columns="right").set_index("family")), ""]
    (E9 / "report.md").write_text("\n".join(lines))
    print("\n".join(lines[:40]))


if __name__ == "__main__":
    main()
