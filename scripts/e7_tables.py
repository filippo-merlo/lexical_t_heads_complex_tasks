"""Tables of paper/e7-attention-filter.tex, and the comparison of the E7 sets with E4's FV sets
(no GPU).

Sources: results/e7_attfilter/{fold1,fold2}/{heads,word_lists}.json, set_sizes.csv
(``scripts/e7_sets.py``); results/e7_attfilter/accuracy_{alpha,crossfit}.csv (``scripts/
e7_report.py``); results/heldout/accuracy_crossfit.csv and fold{1,2}/heads.json (E4);
data/readings/heldout/attention_{A,B} (BOS attention); results/davidson_fv_diff/fv_vs_cc.json
(``scripts/e3/fv_vs_cc_profile.py``).

Computed here, per fold and task, between ``raw_att`` and E4's ``fv20`` / ``fv40``: shared heads,
layer-matched chance (per raw_att head, the share of its layer's heads in the FV set), the FV
heads not in the unfiltered raw set (they do not decode the list), those in it but dropped by the
filter, and the BOS threshold that would keep every FV head of the raw set (the largest BOS
attention among them) with the raw set's size at that threshold. Written to
results/e7_attfilter/fv_compare.json. Accuracies are mean of the two folds at the cross-fitted
alpha, as in ``e7_report.py``.

Writes paper/tables/e7_*.tex (tabulars only).

    .venv/bin/python scripts/e7_tables.py
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from lth import DATA, RESULTS, simple  # noqa: E402

E7 = RESULTS / "e7_attfilter"
TABLES = ROOT / "paper" / "tables"
HEADER = "% Generated by scripts/e7_tables.py; do not edit.\n"
HALF = {1: "A", 2: "B"}


def task_tex(t: str) -> str:
    if t.startswith("english-"):
        return "English--" + t.split("-")[1].title()
    return {"next_item": "next-item", "prev_item": "prev-item"}.get(t, t.replace("-", "--"))


def cell(x, bold=False) -> str:
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "--"
    s = f"{x:.2f}" if isinstance(x, (float, np.floating)) else str(x)
    return f"\\textbf{{{s}}}" if bold else s


def tabular(name: str, cols: list[str], rows: list[list[str]], align: str, mid_before: int | None = None) -> None:
    lines = [HEADER + f"\\begin{{tabular}}{{{align}}}", "\\toprule", " & ".join(cols) + " \\\\", "\\midrule"]
    for i, r in enumerate(rows):
        if mid_before is not None and i == mid_before:
            lines.append("\\midrule")
        lines.append(" & ".join(r) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    (TABLES / f"{name}.tex").write_text("\n".join(lines))


def heads(path: Path) -> dict[str, dict[str, set]]:
    return {t: {n: {tuple(h) for h in hs} for _, n, hs in v["sets"]}
            for t, v in json.loads(path.read_text())["simple"].items()}


def acc_table(name: str, family: str, sets: list[str], labels: list[str], with_control: bool) -> None:
    cf = pd.read_csv(E7 / "accuracy_crossfit.csv")
    cf = cf.assign(set=cf.set.str.replace(r"^(random_(?:drop|layer)_\w+?)_\d$", r"\1", regex=True))
    e4 = pd.read_csv(RESULTS / "heldout" / "accuracy_crossfit.csv")
    e4 = e4.assign(set="E4 " + e4.set)
    x = pd.concat([cf, e4])
    x = x[x.family == family]
    task = x[x.source == "task"].groupby(["task", "set"]).accuracy.mean().unstack()
    ctrl = x[x.source == "control"].groupby(["task", "set"]).accuracy.mean().unstack()
    base = []
    for f in (1, 2):
        for p in (E7 / f"fold{f}").glob(f"patching_{family}.part-main-*.csv"):
            d = pd.read_csv(p)
            base.append(d[d.source == "none"].assign(fold=f))
    base = pd.concat(base).drop_duplicates(["fold", "task"])
    items = base.pivot_table(index="task", columns="fold", values="n_prompts")
    unp = base.groupby("task").accuracy.mean()
    rows = []
    for t in [*simple.TASKS, "mean"]:
        if t == "mean":
            vals = [task[s].mean() for s in sets]
            r = ["\\textbf{mean}", "", cell(unp.mean())]
        else:
            vals = [task.loc[t, s] for s in sets]
            r = [task_tex(t), f"{int(items.loc[t, 1])}/{int(items.loc[t, 2])}", cell(unp[t])]
        top = max(v for v in vals if not np.isnan(v))
        r += [cell(v, bold=(v == top)) for v in vals]
        rows.append(r)
    if with_control:
        rows.append(["control mean", "", ""] + [cell(ctrl[s].mean()) if s in ctrl and not s.startswith("random") else "--"
                                                for s in sets])
    tabular(name, ["Task", "items", "unpatched", *labels], rows, "l" + "r" * (len(labels) + 2), mid_before=len(simple.TASKS))


def main() -> None:
    TABLES.mkdir(exist_ok=True)
    # Word lists (fold 1) and agreement with fold 2.
    W = {f: json.loads((E7 / f"fold{f}" / "word_lists.json").read_text()) for f in (1, 2)}
    rows = []
    for t in simple.TASKS:
        a, b = W[1]["tasks"][t], W[2]["tasks"][t]
        rows.append([task_tex(t), ", ".join(a["raw"]), ", ".join(a["clean"]),
                     f"{len(set(a['raw']) & set(b['raw']))}/{len(set(a['clean']) & set(b['clean']))}"])
    tabular("e7_lists", ["Task", "raw list (fold 1)", "clean list (fold 1)", "fold 2 same"],
            [[r[0], f"\\emph{{{r[1]}}}", f"\\emph{{{r[2]}}}", r[3]] for r in rows],
            ">{\\raggedright\\arraybackslash}p{2.3cm}>{\\raggedright\\arraybackslash}p{5.9cm}>{\\raggedright\\arraybackslash}p{5.9cm}r")
    removed = W[1]["removed"]

    # Set sizes.
    sz = pd.concat([pd.read_csv(E7 / f"fold{f}" / "set_sizes.csv").assign(fold=f) for f in (1, 2)])
    rows = []
    for t in simple.TASKS:
        s = sz[sz.task == t]
        rng = lambda c: f"{s[c].min()}" if s[c].min() == s[c].max() else f"{s[c].min()}--{s[c].max()}"  # noqa: E731
        rows.append([task_tex(t), rng("raw"), rng("raw_att"), rng("raw_att0.4"), rng("raw_att0.6"),
                     cell(s.raw_bos_median.mean()), rng("raw_one_wording"),
                     rng("clean"), rng("clean_att"), cell(s.clean_bos_median.mean()), rng("clean_one_wording")])
    tabular("e7_sizes", ["Task", "raw", "+filter", "at 0.4", "at 0.6", "BOS med.", "one wording",
                         "clean", "+filter", "BOS med.", "one wording"], rows, "lrrrrrrrrrr")

    # Accuracies.
    acc_table("e7_check1", "simple",
              ["raw", "raw_att", "clean", "clean_att", "random_drop_raw", "random_layer_raw", "random_drop_clean",
               "random_layer_clean"],
              ["raw", "raw+F", "clean", "clean+F", "drop raw", "layer raw", "drop clean", "layer clean"], True)
    acc_table("e7_check1_refs", "simple", ["raw_att", "E4 cc", "E4 cc20", "E4 cc40", "E4 fv20", "E4 fv40", "E4 fvNt"],
              ["raw+F", "CC", "CC-20", "CC-40", "FV-20", "FV-40", "FV-$N_t$"], True)
    acc_table("e7_check2", "simple-wrong", ["raw", "raw_att", "clean", "clean_att", "E4 cc", "E4 fv20", "E4 fv40", "E4 fvNt"],
              ["raw", "raw+F", "clean", "clean+F", "CC", "FV-20", "FV-40", "FV-$N_t$"], True)

    # Heads: raw_att vs FV-20 / FV-40.
    out = []
    for f in (1, 2):
        e7, e4 = heads(E7 / f"fold{f}" / "heads.json"), heads(RESULTS / "heldout" / f"fold{f}" / "heads.json")
        for t in simple.TASKS:
            bos = np.load(DATA / "readings" / "heldout" / f"attention_{HALF[f]}" / f"{t}.npy")[:, :, 3].mean(0)
            b = lambda s: np.array([bos[l * 32 + h] for l, h in s])  # noqa: E731
            ra, raw = e7[t]["raw_att"], e7[t]["raw"]
            for k in ("fv20", "fv40"):
                fv = e4[t][k]
                per_layer = Counter(l for l, _ in fv)
                dec = fv & raw
                out.append(dict(fold=f, task=t, fv=k, n_raw_att=len(ra), shared=len(ra & fv),
                                chance=sum(per_layer[l] / 32 for l, _ in ra), not_decoding=len(fv - raw),
                                dropped=len(dec - ra), fv_bos_le05=float(np.mean(b(fv) <= 0.5)),
                                threshold=float(b(dec).max()) if dec else None,
                                size_at_threshold=int((b(raw) <= b(dec).max()).sum()) if dec else None,
                                layer_fv=float(np.median([l for l, _ in fv])), layer_raw_att=float(np.median([l for l, _ in ra])),
                                high_bos_decoding=[f"L{l}H{h}" for l, h in sorted(dec) if bos[l * 32 + h] > 0.5]))
    d = pd.DataFrame(out)
    (E7 / "fv_compare.json").write_text(json.dumps(out, indent=1))
    rows = []
    for t in [*simple.TASKS, "mean"]:
        s = d if t == "mean" else d[d.task == t]
        r = ["\\textbf{mean}" if t == "mean" else task_tex(t), cell(s.n_raw_att.mean())[:-1]]
        for k, n in (("fv20", 20), ("fv40", 40)):
            x = s[s.fv == k]
            r += [cell(x.shared.mean())[:-1], cell(x.chance.mean())[:-1], cell(x.not_decoding.mean())[:-1], cell(x.dropped.mean())[:-1]]
        rows.append(r)
    tabular("e7_overlap", ["Task", "raw+F", "FV-20: shared", "chance", "no decode", "filtered",
                           "FV-40: shared", "chance", "no decode", "filtered"], rows, "lrrrrrrrrr", mid_before=len(simple.TASKS))
    rows = []
    for t in simple.TASKS:
        r = [task_tex(t)]
        for k in ("fv20", "fv40"):
            x = d[(d.task == t) & (d.fv == k)]
            r += [cell(x.threshold.max()), f"{int(x.size_at_threshold.min())}--{int(x.size_at_threshold.max())}"]
        rows.append(r)
    tabular("e7_threshold", ["Task", "FV-20: threshold", "set size", "FV-40: threshold", "set size"], rows, "lrrrr")
    summary = {k: dict(shared=d[d.fv == k].shared.mean(), chance=d[d.fv == k].chance.mean(),
                       not_decoding=d[d.fv == k].not_decoding.mean(), dropped=d[d.fv == k].dropped.mean(),
                       fv_bos_le05=d[d.fv == k].fv_bos_le05.mean(), threshold_median=d[d.fv == k].threshold.median(),
                       layer_fv=d[d.fv == k].layer_fv.mean(), layer_raw_att=d[d.fv == k].layer_raw_att.mean())
               for k in ("fv20", "fv40")}

    # Profile of FV task heads vs CC-only heads (the motivation).
    P = json.loads((RESULTS / "davidson_fv_diff" / "fv_vs_cc.json").read_text())
    med = P["medians"]
    groups = [("task24_dec", "FV task, decode"), ("task24_nodec", "FV task, no decode"), ("cc20_only", "CC-only"),
              ("other_L13_31", "all, L13--31")]
    measures = [("pairs", "heads per task"), ("layer", "layer"), ("att_bos", "attention on BOS"),
                ("att_taskword", "attention on task words"), ("att_input", "attention on the input"),
                ("out_cos", "output alike across tasks"), ("rate", "CC-list match rate"), ("cierank", "FV score rank in task")]
    rows = []
    for key, label in measures:
        vals = [P["pairs_per_task"][g] if key == "pairs" else med[g][key] for g, _ in groups]
        rows.append([label] + [f"{v:.0f}" if key in ("pairs", "layer", "cierank") else f"{v:.2f}" for v in vals])
    tabular("e7_profile", ["", *(lab for _, lab in groups)], rows, "lrrrr")
    (E7 / "tables_summary.json").write_text(json.dumps(dict(removed=removed, fv=summary,
                                                            profile=P["decoders_L13_31"], marker=P["bos_marker"],
                                                            cc_only_top30=P["cc_only_in_task_top30"],
                                                            fv_tasks_in_top30_median=P["fv_tasks_in_top30_median"]), indent=1, default=float))
    print(json.dumps(summary, indent=1, default=float))


if __name__ == "__main__":
    main()
