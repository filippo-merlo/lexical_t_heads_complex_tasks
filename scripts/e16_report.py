"""E16 report: B (low BOS attention) against Sandoval-Segura et al.'s Avg Head Output Norm (LN) as a ranking
filter (scripts/e16_sets.py, e16_patch.sh), check 1.

E13's loading and cross-fit (``e13_report``): accuracy at the cross-fitted alpha over {1, 2}, mean of the
two folds, task accuracy the mean over the five rule means. The B sets are E13's own results
(``results/e13_capped``), patched under the same protocol.

Writes ``results/e16_ahon/{accuracy_alpha,per_task,summary}.csv``, ``paper/tables/e16_main.tex``,
``e16_control.tex`` and ``e16_groups.tex``.

    .venv/bin/python scripts/e16_report.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parent))

import e13_report as e13  # noqa: E402
import results_tex as rt  # noqa: E402
from lth import RESULTS  # noqa: E402

OUT = RESULTS / "e16_ahon"
SIZES = e13.SIZES
PAIRS = (("B", "O"), ("DB", "DO"), ("BT", "OT"), ("DBT", "DOT"))  # (E13 condition, E16 counterpart)
LABEL = {"B": "B", "DB": "DB", "BT": "BT", "DBT": "DBT", "O": "O", "DO": "DO", "OT": "OT", "DOT": "DOT"}


def run_e16() -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    e13.OUT = OUT
    curves, base = e13.load()
    curves.to_csv(OUT / "accuracy_alpha.csv", index=False)
    per, s = e13.summarise(e13.crossfit(curves))
    per.to_csv(OUT / "per_task.csv", index=False)
    s.to_csv(OUT / "summary.csv", index=False)
    return per, s, base


def tex_main(s: pd.DataFrame, value: str, name: str) -> None:
    """Rows: each B condition and its O counterpart; columns: per task and shared at each N. Bold: the
    higher of the pair (check 1 table only)."""
    idx = s.set_index(["condition", "scope", "n"])[value]
    lines = []
    for i, (b, o) in enumerate(PAIRS):
        if i:
            lines.append(r"\addlinespace")
        for cond, other in ((b, o), (o, b)):
            cells = []
            for scope in ("task", "shared"):
                for n in SIZES:
                    v, w = idx.get((cond, scope, n), np.nan), idx.get((other, scope, n), np.nan)
                    cells.append(e13.cell(v, value == "check1_task" and v > w))
            lines.append(LABEL[cond] + " & " + " & ".join(cells) + r" \\")
    header = [r" & \multicolumn{4}{c}{One set per task} & \multicolumn{4}{c}{One set for all 14 tasks} \\",
              r"\cmidrule(lr){2-5}\cmidrule(lr){6-9}",
              r"Heads (N) & " + " & ".join(str(n) for n in SIZES * 2) + r" \\"]
    text = "\n".join([r"\begin{tabular}{@{}l" + "c" * 8 + r"@{}}", r"\toprule", *header, r"\midrule", *lines,
                      r"\bottomrule", r"\end{tabular}"])
    (rt.TABLES / f"{name}.tex").write_text("% Generated by scripts/e16_report.py.\n" + text + "\n")


def tex_groups(per: pd.DataFrame) -> None:
    """Task-type means of DBT and DOT, BT and OT, per task and shared, at every N."""
    cols = [(sc, c) for sc in ("task", "shared") for c in ("BT", "OT", "DBT", "DOT")]
    q = per[per.source == "task"].set_index(["scope", "condition", "n", "task"]).accuracy
    rows = []
    for n in SIZES:
        if rows:
            rows.append(r"\addlinespace")
        rows.append(r"\multicolumn{" + str(len(cols) + 1) + r"}{@{}l}{\textit{" + f"{n} heads" + r"}} \\")
        for group, tasks in e13.GROUPS.items():
            vals = [np.mean([q.get((sc, c, n, t), np.nan) for t in tasks]) for sc, c in cols]
            cells = []
            for i, v in enumerate(vals):
                partner = vals[i + 1] if i % 2 == 0 else vals[i - 1]  # BT|OT, DBT|DOT pairs
                cells.append(e13.cell(v, v > partner))
            rows.append(r"\quad " + group + f" ({len(tasks)}) & " + " & ".join(cells) + r" \\")
    head = [r" & \multicolumn{4}{c}{One set per task} & \multicolumn{4}{c}{One set for all tasks} \\",
            r"\cmidrule(lr){2-5}\cmidrule(lr){6-9}",
            "Task type & " + " & ".join(LABEL[c] for _, c in cols) + r" \\"]
    text = "\n".join([r"\begin{tabular}{@{}l" + "c" * len(cols) + r"@{}}", r"\toprule", *head, r"\midrule", *rows,
                      r"\bottomrule", r"\end{tabular}"])
    (rt.TABLES / "e16_groups.tex").write_text("% Generated by scripts/e16_report.py.\n" + text + "\n")


def main() -> None:
    per16, s16, base16 = run_e16()
    s13 = pd.read_csv(RESULTS / "e13_capped" / "summary.csv")
    per13 = pd.read_csv(RESULTS / "e13_capped" / "per_task.csv")
    b_conds = [b for b, _ in PAIRS]
    s = pd.concat([s13[s13.condition.isin(b_conds)], s16], ignore_index=True)
    per = pd.concat([per13[per13.condition.isin(b_conds)], per16], ignore_index=True)
    tex_main(s, "check1_task", "e16_main")
    tex_main(s, "check1_control", "e16_control")
    tex_groups(per)
    pd.set_option("display.width", 220)
    print(s.pivot_table(index="condition", columns=["scope", "n"], values="check1_task").round(3).to_string())
    print(s.pivot_table(index="condition", columns=["scope", "n"], values="check1_control").round(3).to_string())
    # Tasks on which O beats B, per pair, scope and N.
    t = per[per.source == "task"].pivot_table(index=["scope", "n", "task"], columns="condition", values="accuracy")
    for b, o in PAIRS:
        wins = (t[o] > t[b]).groupby(level=["scope", "n"]).sum()
        ties = (t[o] == t[b]).groupby(level=["scope", "n"]).sum()
        print(f"{o} > {b} on tasks:", {f"{k[0]}{k[1]}": f"{int(v)}/{14 - int(ties[k])}" for k, v in wins.items()})
    print("unpatched", round(base16.accuracy.mean(), 3), "incomplete:", s16[(s16.tasks < 14) | (s16.folds < 2)].set.tolist())


if __name__ == "__main__":
    main()
