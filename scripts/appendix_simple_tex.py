"""LaTeX for proposal-simple's appendix on the simple tasks: term lists and instruction templates.

Writes ``paper/appendix-simple.tex``, ``\\input`` by ``paper/proposal-simple.tex``:
- the term list of each task (Yang et al.'s ``task_relation_dict.json``, ``lth.terms``) and the
  single tokens it expands to under the Llama-3.1 tokenizer (``expand_to_token_ids``), the
  tokens a head's top 10 is matched against;
- the five instruction templates of each task (``lth.simple.instruction_dict``, templates
  0-4), marking the one whose prompts identify the rule-style heads of E1
  (``results/heads.json``).
Characters outside Latin script are printed as Unicode code points (no CJK font here).

    .venv/bin/python scripts/appendix_simple_tex.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from lth import PAPER, RESULTS, simple  # noqa: E402
from lth.terms import expand_to_token_ids, simple_term_lists  # noqa: E402

NAMES = {"antonym": "antonym", "synonym": "synonym", "singular-plural": "singular--plural",
         "present-past": "present--past", "country-capital": "country--capital",
         "country-currency": "country--currency", "landmark-country": "landmark--country",
         "park-country": "park--country", "product-company": "product--company",
         "next_item": "next-item", "prev_item": "prev-item", "english-french": "English--French",
         "english-german": "English--German", "english-spanish": "English--Spanish"}
LETTERS = "ABCDE"
SPECIAL = {"\\": r"\textbackslash{}", "{": r"\{", "}": r"\}", "_": r"\_", "&": r"\&", "%": r"\%",
           "$": r"\$", "#": r"\#", "^": r"\^{}", "~": r"\~{}", "'": r"\textquotesingle{}",
           "\n": r"$\hookleftarrow$"}


def tex(text: str, space: str = " ") -> str:
    """``text`` for ``\\texttt``: specials escaped, non-Latin characters as code points."""
    out = []
    for ch in text:
        if ord(ch) >= 0x2E80:  # spaced, so that a run of code points can break across lines
            out.append((" " if out and out[-1].lstrip().startswith(r"\textrm{U+") else "")
                       + rf"\textrm{{U+{ord(ch):04X}}}")
        elif ch == " ":
            out.append(space)
        else:
            out.append(SPECIAL.get(ch, ch))
    return "".join(out)


def main() -> None:
    from transformers import AutoTokenizer
    from src.config import LENSES

    tokenizer = AutoTokenizer.from_pretrained(LENSES["llama3.1-8b-it"].hf_model_id)
    terms = simple_term_lists()
    heads = json.loads((RESULTS / "heads.json").read_text())["simple"]
    out = ["% Generated by scripts/appendix_simple_tex.py from Yang et al.'s term lists and templates.",
           r"\section{Term lists}\label{app:terms-simple}",
           r"The term list $V_t$ of each task, as in the file of \citet[App.~A.2.1]{yang2026shared}, and the "
           r"single tokens it expands to, as in their code: each term is tried as written, with a leading space, "
           r"in upper, capitalised and lower case, and after a \texttt{.}, \texttt{\_} or \texttt{-}; every "
           r"variant that is one token of the Llama-3.1 tokenizer is kept. A head matches a prompt when one of "
           r"its ten highest-scoring tokens is one of these (Definition~\ref{def:lth}). "
           r"Terms marked $\dagger$ have no variant that is one token, so they never match. "
           r"\textvisiblespace: leading space; U+: a character outside Latin script, by its code point.",
           "", r"\begin{center}\footnotesize\frenchspacing",
           r"\begin{tabular}{@{}l>{\raggedright}p{0.28\textwidth}"
           r">{\raggedright\arraybackslash}p{0.49\textwidth}@{}}",
           r"\toprule", r"Task & Terms & Tokens \\", r"\midrule"]
    for task in simple.TASKS:
        words = [tex(w) + ("$^\\dagger$" if not expand_to_token_ids(tokenizer, [w]) else "")
                 for w in terms[task]]
        ids = expand_to_token_ids(tokenizer, terms[task])
        tokens = sorted({tokenizer.decode([i]) for i in ids}, key=lambda s: (s.strip(" ._-").lower(), s))
        tokens = [r"\texttt{" + tex(s, r"\textvisiblespace{}") + "}" for s in tokens]
        out.append(f"{NAMES[task]} & {', '.join(words)} & {', '.join(tokens)} ({len(ids)}) \\\\[2pt]")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{center}", ""]

    out += [r"\section{Instruction templates}\label{app:templates-simple}",
            r"\begin{sloppypar}The five instruction templates of each task, the rule-style prompts of "
            r"\citet[App.~A.3.1]{yang2026shared} (templates A--E, the first five of their instruction file). "
            r"\texttt{\{input\}} is replaced by the item and the prompt ends after the last character shown; "
            r"$\hookleftarrow$: newline. $^\ast$: the template whose prompts identify the rule-style heads of E1, "
            r"the most accurate under the flexible score (Sec.~\ref{sec:e1}); E1b uses all five. "
            r"Example-style prompts have no instruction: $n$ items of the dataset as "
            r"``\texttt{\textvisiblespace\{input\}:\textvisiblespace\{output\};}'', followed by the query as "
            r"``\texttt{\textvisiblespace\{input\}:}'' (\textvisiblespace: space), for instance the 1-shot "
            r"antonym prompt ``\texttt{" + tex(simple.prompts("antonym", "shot1")[0][0], r"\textvisiblespace{}")
            + r"}''; the zero-shot prompt is the query alone.\end{sloppypar}",
            "", r"{\footnotesize\frenchspacing",
            r"\begin{longtable}{@{}ll>{\raggedright\arraybackslash}p{0.74\textwidth}@{}}",
            r"\toprule", r"Task & & Template \\", r"\midrule", r"\endhead", r"\bottomrule", r"\endfoot"]
    templates = simple.instruction_dict()
    for task in simple.TASKS:
        (chosen,) = heads[task]["rule"]["logithead"]["wordings"]
        assert heads[task]["rule"]["jhead"]["wordings"] == [chosen]
        for i in simple.INSTRUCTIONS:
            mark = "$^\\ast$" if f"inst{i}" == chosen else ""
            name = NAMES[task] if i == 0 else ""
            end = r" \\[3pt]" if i == simple.INSTRUCTIONS[-1] else r" \\"
            out.append(f"{name} & {LETTERS[i]}{mark} & \\texttt{{{tex(templates[task][str(i)])}}}{end}")
    out += [r"\end{longtable}", "}"]
    (PAPER / "appendix-simple.tex").write_text("\n".join(out) + "\n")
    print("wrote appendix-simple.tex")


if __name__ == "__main__":
    main()
