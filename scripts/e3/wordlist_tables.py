"""Write paper/tables/wordlists_jhead{,_control}.tex from the light check-1 runs (J-head, rule means,
best alpha of 1,2,4,8): E1, CC-pooled, CC-pooled-clean, attend+decode top 1/5/20 and its random 5."""
import sys, pandas as pd
sys.path.insert(0, ".")
from lth import simple
B = pd.read_csv(sys.argv[1]); E = pd.read_csv("results/best_design_per_task.csv")
e1 = E[E.design == "E1: Yang list, best wording"].set_index("task")
cols = [("E1", None), ("CC-pooled", "union_alllist_allid"), ("CC-pooled-clean", "neutral_5+5"),
        ("A+D 1", "ad_top1"), ("A+D 5", "ad_top5"), ("A+D 20", "ad_top20"), ("random 5", ("ad_top5_random0", "ad_top5_random1"))]
base = B.groupby("task").base.first()
NAME = {"next_item": "next-item", "prev_item": "prev-item", "english-french": "English--French", "english-german": "English--German", "english-spanish": "English--Spanish"}
def val(t, key, what):
    if key is None: return e1.loc[t, "acc" if what == "acc" else "control"]
    keys = key if isinstance(key, tuple) else (key,)
    x = B[(B.task == t) & B.heads.isin(keys)]
    if "union_alllist_allid" in keys: x = x[x.dir == "word_lists_union"]
    return x[what].mean()
for what, out in (("acc", "wordlists_jhead"), ("ctl", "wordlists_jhead_control")):
    rows = []; vals = {c: [] for c, _ in cols}
    for t in simple.TASKS:
        v = [val(t, k, what) for _, k in cols]
        for (c, _), x in zip(cols, v): vals[c].append(x)
        best = max(v[:6]) if what == "acc" else None
        cells = [(r"\textbf{%.2f}" if (what == "acc" and abs(x - best) < 1e-9 and i < 6) else "%.2f") % x for i, x in enumerate(v)]
        rows.append(f"{NAME.get(t, t.replace('-', '--'))} & {base[t]:.2f} & " + " & ".join(cells) + r" \\")
    head = "% Generated by scripts/e3/wordlist_tables.py from results/.\n" + r"\begin{tabular}{lrrrrrrrr}" + "\n\\toprule\nTask & unpatched & " + " & ".join(c for c, _ in cols) + r" \\" + "\n\\midrule\n"
    mean = r"\midrule" + "\nmean & %.2f & " % base.mean() + " & ".join("%.2f" % (sum(vals[c]) / len(vals[c])) for c, _ in cols) + r" \\"
    open(f"paper/tables/{out}.tex", "w").write(head + "\n".join(rows) + "\n" + mean + "\n\\bottomrule\n\\end{tabular}\n")
    print(open(f"paper/tables/{out}.tex").read())
