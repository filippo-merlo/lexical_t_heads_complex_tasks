"""Rebuilt design (paper/head-sets-simple-design.tex, Sec. 3.2): split the prompt material once into
a choosing part P and a test part Q, before any run. The documents call P the identification wordings /
formats and Q the test wordings / formats; the code, the split file and the run options keep the keys P and Q.

- **Wordings.** The 30 further wordings of each task (``lth.simple.E4B_WORDINGS``: six groups of five,
  form x whether the wording names the task) go 15 to P and 15 to Q. In every form one group gives
  three wordings to P and the other two, so P holds five wordings of each form. Which group gives three
  alternates between forms (cloze: named, question--answer: unnamed, label: named) and is swapped on
  every other task (``lth.simple.TASKS`` order), so P holds 8 wordings that name the task on half of the
  tasks and 7 on the other half. Within a group the wordings are drawn at random (seed 0, task, group).
- **Example formats.** P: F1, F2, F3; Q: F4, F5, F6 (``lth.simple.EXAMPLE_FORMATS``).

Writes ``materials/simple/prompt_split.json`` and ``paper/tables/design_wordings.tex`` (the split of
every task, for the paper's appendix). ``--show`` prints one item's prompt in every example format for
the given tasks, with its demonstrations drawn from its half (``results/heldout/split.json``).

    .venv/bin/python scripts/rebuild_prompt_split.py
    .venv/bin/python scripts/rebuild_prompt_split.py --show antonym country-capital
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from lth import MATERIALS, RESULTS, ROOT, simple  # noqa: E402

OUT = MATERIALS / "simple" / "prompt_split.json"
TABLE = ROOT / "paper" / "tables" / "design_wordings.tex"
SEED = 0
# P's share of each group on even-indexed tasks; odd-indexed tasks take the complement (5 - n).
P_EVEN = {"cloze-named": 3, "cloze-unnamed": 2, "qa-named": 2, "qa-unnamed": 3,
          "label-named": 3, "label-unnamed": 2}
FORMATS = {"P": ["F1", "F2", "F3"], "Q": ["F4", "F5", "F6"]}
GROUP_NAMES = {"cloze-named": "cloze, names the task", "cloze-unnamed": "cloze, does not name it",
               "qa-named": "question--answer, names the task", "qa-unnamed": "question--answer, does not name it",
               "label-named": "label, names the task", "label-unnamed": "label, does not name it"}


def split_wordings() -> dict[str, dict[str, list[str]]]:
    out = {}
    for k, task in enumerate(simple.TASKS):
        parts = {"P": [], "Q": []}
        for g, cell in enumerate(simple.E4B_CELLS):
            n = P_EVEN[cell] if k % 2 == 0 else 5 - P_EVEN[cell]
            rng = np.random.default_rng([SEED, k, g])
            chosen = set(int(i) for i in rng.choice(5, size=n, replace=False))
            for i in range(5):
                parts["P" if i in chosen else "Q"].append(f"{simple.E4B_PREFIX}{cell}-{i}")
        assert len(parts["P"]) == len(parts["Q"]) == 15
        out[task] = parts
    return out


def tex(s: str) -> str:
    return s.replace("{input}", r"\{x\}").replace("\n", r"\nl ")


def table(wordings: dict[str, dict[str, list[str]]]) -> str:
    templates = simple.e4b_templates()
    lines = ["% Generated by scripts/rebuild_prompt_split.py.",
             r"\begin{xltabular}{\textwidth}{@{}>{\raggedright\arraybackslash}p{2.6cm}LL@{}}",
             r"\caption{The 30 further wordings of every task, by group: the identification wordings are used to identify heads, the test wordings only for the means patched in the test.}\label{tab:wording-split}\\",
             r"\toprule Group & Identification & Test \\ \midrule \endfirsthead",
             r"\toprule Group & Identification & Test \\ \midrule \endhead",
             r"\bottomrule \endlastfoot"]
    for task in simple.TASKS:
        lines.append(rf"\multicolumn{{3}}{{@{{}}l}}{{\textit{{{task.replace('_', '-')}}}}} \\")
        for cell in simple.E4B_CELLS:
            cells = []
            for part in ("P", "Q"):
                ids = [w for w in wordings[task][part] if simple.wording_group(w) == cell]
                cells.append(r" \newline ".join(r"\texttt{" + tex(templates[task][w]) + "}" for w in ids))
            lines.append(f"{GROUP_NAMES[cell]} & {cells[0]} & {cells[1]} \\\\")
        lines.append(r"\midrule")
    lines[-1] = ""
    lines.append(r"\end{xltabular}")
    return "\n".join(lines) + "\n"


def show(tasks: list[str]) -> None:
    halves = json.loads((RESULTS / "heldout" / "split.json").read_text())
    for task in tasks:
        data = simple.dataset(task)
        pool = halves[task]["A"]
        item = pool[0]
        demos = simple.demo_items(task, item, pool)
        print(f"=== {task}, item {item} (half A), demonstrations {demos}")
        for fmt in simple.EXAMPLE_FORMATS:
            prompt, answer = simple.example_prompt(data, fmt, demos, item)
            print(f"--- {fmt}: answer {answer!r}\n{prompt}")
        print()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--show", nargs="+", default=None, help="print example prompts for these tasks")
    args = parser.parse_args()
    if args.show:
        show(args.show)
        return
    wordings = split_wordings()
    OUT.write_text(json.dumps({"note": __doc__.split("\n\n")[0], "seed": SEED,
                               "wordings": wordings, "formats": FORMATS}, indent=1) + "\n")
    TABLE.write_text(table(wordings))
    for task in simple.TASKS:
        named = sum(simple.wording_group(w).endswith("-named") for w in wordings[task]["P"])
        print(f"{task:18s} P: {named} naming the task, {15 - named} not")
    print(f"wrote {OUT.relative_to(ROOT)} and {TABLE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
