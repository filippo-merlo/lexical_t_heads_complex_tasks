import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

from lth import RESULTS, simple  # noqa: E402

SIZED = RESULTS / "sized"
SIZES = (5, 10, 20)
READOUTS = ("logithead", "jhead")
RULES = ("e1", "k1", "k3", "k5")
CHECKS = (("simple", "first check"), ("simple-wrong", "second check"))
THRESHOLD_DIRS = {"k1": "consensus_k1", "k3": "consensus_k3", "k5": "consensus"}
RULE_LABEL = {"e1": "E1", "k1": "$k=1$", "k3": "$k=3$", "k5": "$k=5$"}
RULE_COLOUR = {"e1": INK, "k1": MAGENTA, "k3": GREEN, "k5": YELLOW}
READOUT_COLOUR = {"logithead": ORANGE, "jhead": BLUE}
READOUT_SHORT = {"logithead": "L", "jhead": "J"}


def write(name: str, text: str) -> None:
    rt.TABLES.mkdir(exist_ok=True)
    (rt.TABLES / f"{name}.tex").write_text(f"% Generated by scripts/sized_tex.py from results/.\n{text}")


def curves(directory: Path, alphas=None) -> pd.DataFrame:
    """Same-style curves of a result folder's simple checks; with ``alphas``, only those rows
    (and the baselines)."""
    frames = [pd.read_csv(f) for f in sorted(directory.glob("patching_*.csv"))]
    frames = [f[f.family.isin(rt.SIMPLE_FAMILIES)] for f in frames if "mean_wording" in f]
    patching = pd.concat(frames, ignore_index=True)
    if alphas is not None:
        patching = patching[(patching.source == "none") | patching.alpha.isin(alphas)]
    same, _ = wording_curves(patching)
    return same


def effect_table(c: pd.DataFrame) -> dict:
    """``(family, task, style, heads, source)`` -> causal effect."""
    return rt.effects(c)


def load() -> tuple[dict, dict, pd.DataFrame]:
    """Equal-size effects ``(family, task, style, readout, rule, N, source)``, threshold-set
    effects ``(family, task, style, readout, rule, source)`` with their sizes, and the measures."""
    sized_curves = curves(SIZED)
    alphas = sorted(sized_curves.alpha.dropna().unique())
    sized = {}
    for (family, task, style, heads, source), value in effect_table(sized_curves).items():
        readout, rule, n = heads.split("|")
        sized[(family, task, style, readout, rule, int(n), source)] = value
    threshold = {}
    for (family, task, style, heads, source), value in effect_table(curves(RESULTS, alphas)).items():
        if heads in READOUTS:
            threshold[(family, task, style, heads, "e1", source)] = value
    for rule, d in THRESHOLD_DIRS.items():
        for (family, task, style, heads, source), value in effect_table(curves(RESULTS / d, alphas)).items():
            if heads in READOUTS and style == "rule":
                threshold[(family, task, style, heads, rule, source)] = value
    return sized, threshold, pd.read_csv(SIZED / "measures.csv")


def threshold_sizes(measures: pd.DataFrame) -> dict:
    """``(task, style, readout, rule)`` -> size of the threshold set."""
    first = measures.drop_duplicates(["task", "style", "rule", "readout"])
    return {(r.task, r.style, r.readout, r.rule): int(r.n_threshold) for r in first.itertuples()}


def table_readouts(sized: dict) -> None:
    sizes = " & ".join(rf"\multicolumn{{2}}{{c}}{{$N={n}$}}" for n in SIZES)
    rules = "".join(rf"\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(2 * len(SIZES)))
    for name, family, source in (("sized_readouts", "simple", "task"), ("sized_readouts_wrong", "simple-wrong", "task"),
                                 ("sized_readouts_control", "simple", "control")):
        header = [" & " + " & ".join(rf"\multicolumn{{6}}{{c}}{{{s} style}}" for s in ("Rule", "Example")) + r" \\",
                  r"\cmidrule(lr){2-7}\cmidrule(lr){8-13}", f" & {sizes} & {sizes}" + r" \\", rules,
                  "Task" + " & L & J" * 2 * len(SIZES) + r" \\"]
        rows = []
        for task in simple.TASKS:
            cells = [num(sized.get((family, task, style, readout, "e1", n, source)))
                     for style in ("rule", "example") for n in SIZES for readout in READOUTS]
            rows.append(" & ".join([tex_name("simple", task), *cells]) + r" \\")
        write(name, tabular("@{}l" + "c" * 12 + "@{}", header, rows))


def table_rules(sized: dict) -> None:
    sizes = " & ".join(rf"\multicolumn{{4}}{{c}}{{$N={n}$}}" for n in SIZES)
    rules = "".join(rf"\cmidrule(lr){{{2 + 4 * i}-{5 + 4 * i}}}" for i in range(len(SIZES)))
    for name, family in (("sized_rules", "simple"), ("sized_rules_wrong", "simple-wrong")):
        header = [f" & {sizes}" + r" \\", rules, "Task" + "".join(f" & {RULE_LABEL[r]}" for r in RULES) * len(SIZES) + r" \\"]
        rows = []
        for readout in READOUTS:
            rows.append(rf"\multicolumn{{13}}{{@{{}}l}}{{\emph{{{rt.SET_LABEL[readout]}}}}} \\")
            for task in simple.TASKS:
                cells = [num(sized.get((family, task, "rule", readout, rule, n, "task"))) for n in SIZES for rule in RULES]
                rows.append(" & ".join([tex_name("simple", task), *cells]) + r" \\")
        write(name, tabular("@{}l" + "c" * 12 + "@{}", header, rows))


def compare(sized: dict, threshold: dict, family: str, task: str, a: tuple, b: tuple) -> tuple[str | None, str]:
    """Which of two sets ``(style, readout, rule)`` has the larger effect between the threshold
    sets ('a', 'b' or None for a tie or a missing set), and at equal size: 'holds' if the same one
    is larger at every N where both are formed, 'reverses' if the other is at every such N,
    'mixed' otherwise, 'none' if no size has both."""
    ta, tb = (threshold.get((family, task, *x, "task")) for x in (a, b))
    winner = None if ta is None or tb is None or ta == tb else ("a" if ta > tb else "b")
    signs = []
    for n in SIZES:
        sa, sb = (sized.get((family, task, x[0], x[1], x[2], n, "task")) for x in (a, b))
        if sa is not None and sb is not None:
            signs.append("a" if sa > sb else "b" if sb > sa else "=")
    if not signs:
        return winner, "none"
    if winner and all(s == winner for s in signs):
        return winner, "holds"
    if winner and all(s not in (winner, "=") for s in signs):
        return winner, "reverses"
    return winner, "mixed"


def table_summary(sized: dict, threshold: dict) -> pd.DataFrame:
    pairs = [(f"J-head vs Logit-head, {style} style", (style, "jhead", "e1"), (style, "logithead", "e1"))
             for style in ("rule", "example")]
    pairs += [(f"{RULE_LABEL[k]} vs E1, {rt.SET_LABEL[readout]}", ("rule", readout, k), ("rule", readout, "e1"))
              for readout in READOUTS for k in ("k1", "k3", "k5")]
    records = []
    for label, a, b in pairs:
        for family, check in CHECKS:
            for task in simple.TASKS:
                winner, verdict = compare(sized, threshold, family, task, a, b)
                records.append(dict(pair=label, check=check, task=task, winner=winner, verdict=verdict))
    df = pd.DataFrame(records)
    rows = []
    for label, *_ in pairs:
        cells = []
        for _, check in CHECKS:
            d = df[(df.pair == label) & (df.check == check)]
            for side in ("a", "b"):
                w = d[d.winner == side]
                cells.append(f"{len(w)} / {int((w.verdict == 'holds').sum())} / {int((w.verdict == 'reverses').sum())}")
        rows.append(" & ".join([label, *cells]) + r" \\")
    first, second = (rf"\multicolumn{{2}}{{c}}{{{c.capitalize()}}}" for _, c in CHECKS)
    header = [f" & {first} & {second}" + r" \\", r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
              r"Pair (first vs second) & first larger & second larger & first larger & second larger \\"]
    write("sized_summary", tabular("@{}lcccc@{}", header, rows))
    return df


def figure(sized: dict, threshold: dict, sizes: dict, name: str, series: list) -> None:
    """Effect against set size per task and check; ``series``: (style, readout, rule, colour,
    dashed, label). The threshold set is a hollow marker at its own size."""
    fig, axes = plt.subplots(7, 4, figsize=(6.3, 8.4), sharex=True, sharey=True)
    for i, task in enumerate(simple.TASKS):
        for j, (family, check) in enumerate(CHECKS):
            ax = axes[i // 2, 2 * (i % 2) + j]
            for style, readout, rule, colour, dashed, _ in series:
                xs = [n for n in SIZES if (family, task, style, readout, rule, n, "task") in sized]
                ax.plot(xs, [sized[(family, task, style, readout, rule, n, "task")] for n in xs], color=colour,
                        lw=1.2, ls=(0, (3, 1.5)) if dashed else "-", marker="o", ms=2.5, zorder=3)
                t = threshold.get((family, task, style, readout, rule, "task"))
                size = sizes.get((task, style, readout, rule))
                if t is not None and size:
                    ax.plot([size], [t], marker="o", ms=4, mfc="none", mec=colour, mew=1.0, ls="none", zorder=4)
            ax.set_title(f"{plot_name('simple', task)}, {check.split()[0]}", loc="left", fontsize=7)
            ax.set_xscale("log")
            ax.set_xticks([5, 10, 20, 50], ["5", "10", "20", "50"])
            ax.minorticks_off()
            ax.set_ylim(-0.05, 1.03)
            style_axes(ax)
    for ax in axes[-1]:
        ax.set_xlabel("heads in the set")
    for ax in axes[:, 0]:
        ax.set_ylabel("effect")
    handles = [plt.Line2D([], [], color=c, ls=(0, (3, 1.5)) if d else "-", marker="o", ms=2.5) for *_, c, d, _ in series]
    labels = [label for *_, label in series]
    handles.append(plt.Line2D([], [], color=INK_2, marker="o", ms=4, mfc="none", ls="none"))
    labels.append("threshold set, at its size")
    fig.legend(handles, labels, loc="upper center", ncol=3)
    fig.tight_layout(rect=(0, 0, 1, 0.955))
    fig.savefig(rt.FIGURES / f"{name}.pdf")
    plt.close(fig)


def main() -> None:
    sized, threshold, measures = load()
    table_readouts(sized)
    table_rules(sized)
    df = table_summary(sized, threshold)
    df.to_csv(SIZED / "comparison.csv", index=False)
    sizes = threshold_sizes(measures)
    figure(sized, threshold, sizes, "sized_readouts",
           [(s, r, "e1", READOUT_COLOUR[r], s == "example", f"{rt.SET_LABEL[r]}, {s}") for s in ("rule", "example") for r in READOUTS])
    for readout in READOUTS:
        figure(sized, threshold, sizes, f"sized_rules_{readout}",
               [("rule", readout, rule, RULE_COLOUR[rule], False, RULE_LABEL[rule].replace("$", "")) for rule in RULES])
    print(f"wrote sized tables to {rt.TABLES}, figures to {rt.FIGURES}, {SIZED}/comparison.csv")


if __name__ == "__main__":
    main()
