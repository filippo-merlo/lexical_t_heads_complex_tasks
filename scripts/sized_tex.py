"""Tables and figures of the equal-size experiment (proposal-simple, Sec. "Head sets of equal
size"), from ``results/sized`` (``scripts/rank_heads.py``, ``scripts/patch.py --set-list``) and
the threshold sets of E1 and E1b (no GPU).

The causal effect is as in ``scripts/results_tex.py``: the highest accuracy over alpha, after
averaging over the source wordings of the set's own style, minus the unpatched accuracy. The
equal-size sets are patched at a subset of E1's alphas; the threshold sets' effects are taken
over the same subset.

Writes ``paper/tables/``:
- ``sized_readouts``, ``sized_readouts_wrong``: Logit-head and J-head effects at N = 5, 10, 20,
  E1's rule, both styles (first and second check); ``sized_readouts_control``: the control
  mean's effect at the same sets (first check);
- ``sized_rules``, ``sized_rules_wrong``: E1 and E1b rules (k = 1, 3, 5) at each N, rule style,
  one block per readout;
- ``sized_summary``: the comparison of the design. For each pair (J-head against Logit-head;
  each k against E1), task and check: which set has the larger effect between the threshold
  sets, and whether the same one has it at every N where both equal-size sets are formed.
And ``paper/figures/sized_readouts.pdf``, ``sized_rules_logithead.pdf``,
``sized_rules_jhead.pdf``: effect against set size, with the threshold sets drawn at their own
sizes; ``results/sized/comparison.csv``: the comparison per pair, check and task.

    .venv/bin/python scripts/sized_tex.py
"""

