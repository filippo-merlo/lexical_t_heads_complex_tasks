"""Per-task result tables for paper/best-approaches.tex, gathered from existing outputs.

No number is recomputed here: every cell is copied from a file another script wrote.
Sources:
  paper/tables/heldout_{check1,check2}_{nt,secondary}.tex   (scripts/heldout_report.py, E4)
  results/davidson_fv_split/report.md                       (scripts/e3/fv_split_report.py)
  results/llm_heads/table_{task}.md                         (scripts/llm_heads_report.py, E5)
Writes paper/tables/best_{check1,check2,fvsplit,llm}.tex (tabulars only).

    python3 scripts/best_approaches_tables.py
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / "paper" / "tables"
HEADER = "% Generated by scripts/best_approaches_tables.py; do not edit.\n"


def read_tex(name: str) -> tuple[list[str], dict[str, dict[str, str]]]:
    """Columns and rows (keyed by task, incl. 'Mean') of a generated tabular."""
    cols, rows = None, {}
    for line in (TABLES / f"{name}.tex").read_text().splitlines():
        if "&" not in line:
            continue
        cells = [c.strip() for c in line.rstrip().rstrip("\\").split("&")]
        if cols is None:
            cols = cells
            continue
        rows[cells[0]] = dict(zip(cols, cells))
    return cols, rows


def md_key(task_tex: str) -> str:
    """'country--capital' -> 'country-capital'; 'next-item' -> 'next_item'; translations lowercased."""
    k = task_tex.replace("--", "-").lower()
    return {"next-item": "next_item", "prev-item": "prev_item"}.get(k, k)


def fmt(x: float) -> str:
    return f"{x:.2f}"


def bold_max(values: list[str]) -> list[str]:
    nums = [float(v) for v in values]
    top = max(nums)
    return [f"\\textbf{{{v}}}" if float(v) == top else v for v in values]


def fv_split() -> dict[str, dict[str, float]]:
    text = (ROOT / "results/davidson_fv_split/report.md").read_text()
    block = text.split("## Best alpha per task")[1].split("\nMean:")[0]
    out = {}
    for line in block.splitlines():
        if not line.startswith("| ") or line.startswith("| task") or line.startswith("|---"):
            continue
        c = [x.strip() for x in line.strip("|").split("|")]
        out[c[0]] = {"all30": float(c[1]), "task24": float(c[2]),
                     "drop6": sum(float(x) for x in c[3:6]) / 3, "generic6": float(c[6]),
                     "a_all30": c[7], "a_task24": c[8]}
    return out


def llm_rows(task: str) -> dict[str, dict[str, str]]:
    out = {}
    for line in (ROOT / f"results/llm_heads/table_{task}.md").read_text().splitlines():
        if not line.startswith("| ") or line.startswith("| set") or line.startswith("|---"):
            continue
        c = [x.strip() for x in line.strip("|").split("|")]
        out[c[0]] = {"heads": c[1], "c1": c[2], "c1ctrl": c[3], "c2": c[4], "c2ctrl": c[5]}
    return out


def main() -> None:
    _, c1 = read_tex("heldout_check1_nt")
    _, c1s = read_tex("heldout_check1_secondary")
    _, c2 = read_tex("heldout_check2_nt")
    _, c2s = read_tex("heldout_check2_secondary")
    split = fv_split()
    tasks = [t for t in c1 if t != "Mean"]

    # --- check 1, every approach -------------------------------------------------
    lines = [HEADER, "\\begin{tabular}{l rrrr r rrr rr}", "\\toprule",
             " & \\multicolumn{4}{c}{held-out} & & \\multicolumn{3}{c}{one fold} & \\multicolumn{2}{c}{same items} \\\\",
             "\\cmidrule(lr){2-5}\\cmidrule(lr){7-9}\\cmidrule(lr){10-11}",
             "Task & E1 & CC & FV-30 & FV-$N_t$ & Random & CC-clean & A+D-20 & FV-univ-20 & FV-30 & task24 \\\\",
             "\\midrule"]
    sums = {"all30": 0.0, "task24": 0.0}
    for t in tasks:
        r, s, f = c1[t], c1s[t], split[md_key(t)]
        main4 = bold_max([r["E1"], r["CC"], r["FV-30 ($\\alpha{=}1$)"], r["FV-$N_t$"]])
        sums["all30"] += f["all30"]
        sums["task24"] += f["task24"]
        lines.append(" & ".join([t, *main4, r["Random-$N_t$"], s["CC-clean"], s["A+D-20"],
                                 s["FV-univ-20"], fmt(f["all30"]), fmt(f["task24"])]) + " \\\\")
    m, ms = c1["Mean"], c1s["Mean"]
    lines += ["\\midrule",
              " & ".join(["Mean", m["E1"], m["CC"], m["FV-30 ($\\alpha{=}1$)"], m["FV-$N_t$"], m["Random-$N_t$"],
                          ms["CC-clean"], ms["A+D-20"], ms["FV-univ-20"],
                          fmt(sums["all30"] / len(tasks)), fmt(sums["task24"] / len(tasks))]) + " \\\\",
              " & ".join(["Control mean", m["E1 ctrl"], m["CC ctrl"], "", m["FV-$N_t$ ctrl"], "", "", "", "", "", ""]) + " \\\\",
              "\\bottomrule", "\\end{tabular}"]
    (TABLES / "best_check1.tex").write_text("\n".join(lines) + "\n")

    # --- check 2 ------------------------------------------------------------------
    lines = [HEADER, "\\begin{tabular}{lr rrrr rr rrr}", "\\toprule",
             " & & \\multicolumn{4}{c}{held-out} & \\multicolumn{2}{c}{one fold} & \\multicolumn{3}{c}{control mean} \\\\",
             "\\cmidrule(lr){3-6}\\cmidrule(lr){7-8}\\cmidrule(lr){9-11}",
             "Task & items & E1 & CC & FV-$N_t$ & Random & A+D-20 & FV-univ-20 & E1 & CC & FV-$N_t$ \\\\",
             "\\midrule"]
    for t in [*tasks, "Mean"]:
        if t == "Mean":
            lines.append("\\midrule")
        r, s = c2[t], c2s[t]
        main3 = [r["E1"], r["CC"], r["FV-$N_t$"]]
        if t != "Mean":
            main3 = bold_max(main3)
        lines.append(" & ".join([t, r["items"], *main3, r["Random-$N_t$"], s["A+D-20"], s["FV-univ-20"],
                                 r["E1 ctrl"], r["CC ctrl"], r["FV-$N_t$ ctrl"]]) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (TABLES / "best_check2.tex").write_text("\n".join(lines) + "\n")

    # --- FV split -----------------------------------------------------------------
    lines = [HEADER, "\\begin{tabular}{l rrrr rr}", "\\toprule",
             "Task & all30 & task24 & generic6 & drop-6 random & $\\alpha$ all30 & $\\alpha$ task24 \\\\", "\\midrule"]
    acc = {k: 0.0 for k in ("all30", "task24", "generic6", "drop6")}
    for t in tasks:
        f = split[md_key(t)]
        for k in acc:
            acc[k] += f[k]
        vals = bold_max([fmt(f["all30"]), fmt(f["task24"])])
        lines.append(" & ".join([t, *vals, fmt(f["generic6"]), fmt(f["drop6"]), f["a_all30"], f["a_task24"]]) + " \\\\")
    lines += ["\\midrule",
              " & ".join(["Mean", *(fmt(acc[k] / len(tasks)) for k in ("all30", "task24", "generic6", "drop6")), "", ""]) + " \\\\",
              "\\bottomrule", "\\end{tabular}"]
    (TABLES / "best_fvsplit.tex").write_text("\n".join(lines) + "\n")

    # --- E5 LLM-scored heads, two tasks --------------------------------------------
    lines = [HEADER, "\\begin{tabular}{ll rrrrr rrr}", "\\toprule",
             " & & \\multicolumn{5}{c}{check 1} & \\multicolumn{3}{c}{check 2} \\\\",
             "\\cmidrule(lr){3-7}\\cmidrule(lr){8-10}",
             "Task & Heads & LLM-J & LLM-L & CC & FV & Random & LLM-J & CC & FV \\\\", "\\midrule"]
    for task, label in (("country-capital", "country--capital"), ("english-german", "English--German")):
        rows = llm_rows(task)
        first = True
        for n in ("20", "30", "40", "60", "80", "Nt"):
            j = rows.get(f"allJ{n}")
            if j is None:
                continue
            l = rows.get(f"allL{n}")
            cc = rows["cc" if n == "Nt" else f"cc{n}"]
            fv = rows[f"fv{n}"]
            rnd = rows.get(f"random_allJ{n}")
            heads = (j["heads"] if n == "Nt" else n).replace("-", "--")
            lines.append(" & ".join([label if first else "", heads, j["c1"], l["c1"] if l else "--", cc["c1"], fv["c1"],
                                     rnd["c1"] if rnd else "--", j["c2"], cc["c2"], fv["c2"]]) + " \\\\")
            first = False
        e1 = rows["e1"]
        e1_heads = e1["heads"].replace("-", "--")
        lines.append(f"\\multicolumn{{10}}{{@{{}}l}}{{\\footnotesize\\quad E1 set ({e1_heads} heads): check 1 {e1['c1']}, check 2 {e1['c2']}}} \\\\")
        if task == "country-capital":
            lines.append("\\midrule")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (TABLES / "best_llm.tex").write_text("\n".join(lines) + "\n")
    print("wrote", *(f"best_{n}.tex" for n in ("check1", "check2", "fvsplit", "llm")))


if __name__ == "__main__":
    main()
