"""Rebuilt design (paper/head-sets-simple-design.tex, App. D): unpatched accuracy of every prompt family on
each half, and the counts the design rests on.

Per task and half (``results/heldout/split.json``), on the first 500 items of the half (those the 30
further wordings and the example formats were run on): the flexible accuracy and the number of correctly
answered prompts of Yang et al.'s five templates, the 15 P and 15 Q wordings
(``materials/simple/prompt_split.json``) and the six example formats; the patched items (answered
correctly 1-shot, at most 100) and the accuracy of their zero-shot prompt " x:". Means take the first
100 correctly answered prompts of a template on the choosing half, so a template with fewer gives a mean
over fewer prompts, and one with none gives no mean.

Writes ``results/rebuild/prompts/accuracy.csv`` (one row per task, half and prompt),
``results/rebuild/prompts/summary.csv`` (one row per task and half) and
``paper/tables/design_unpatched.tex``.

    .venv/bin/python scripts/rebuild_prompt_table.py
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from lth import RESULTS, ROOT, simple  # noqa: E402
from lth.store import load, readings_dir  # noqa: E402

OUT = RESULTS / "rebuild" / "prompts"
TABLE = ROOT / "paper" / "tables" / "design_unpatched.tex"
N_PER_HALF = 500
CAP = 100
FEW = 30


def records(task: str, wording: str) -> dict[int, bool] | None:
    directory = readings_dir("simple", task)
    if not (directory / f"{wording}.json").exists():
        return None
    return {int(r["item"]): bool(r["correct"]) for r in load(directory, wording)["records"]}


def main() -> None:
    split = json.loads((RESULTS / "heldout" / "split.json").read_text())
    parts = simple.prompt_split()
    OUT.mkdir(parents=True, exist_ok=True)
    rows, summary = [], []
    for task in simple.TASKS:
        families = {"yang": list(simple.WORDINGS["rule"]), "P": parts["wordings"][task]["P"],
                    "Q": parts["wordings"][task]["Q"],
                    "F-P": [f"{simple.FORMAT_PREFIX}{f}" for f in parts["formats"]["P"]],
                    "F-Q": [f"{simple.FORMAT_PREFIX}{f}" for f in parts["formats"]["Q"]]}
        recs = {w: records(task, w) for ws in families.values() for w in ws}
        shot1, zero = records(task, "shot1"), records(task, "zero")
        for half in ("A", "B"):
            items = sorted(split[task][half])[:N_PER_HALF]
            patched = [i for i in sorted(split[task][half]) if shot1[i]][:CAP]
            row = {"task": task, "half": half, "items": len(split[task][half]), "patched": len(patched),
                   "zero_shot_accuracy": round(sum(zero[i] for i in patched) / len(patched), 3)}
            for family, wordings in families.items():
                accs, few, none = [], 0, 0
                for w in wordings:
                    r = recs[w]
                    if r is None:
                        continue
                    correct = sum(r[i] for i in items)
                    accs.append(correct / len(items))
                    few += correct < FEW
                    none += correct == 0
                    rows.append({"task": task, "half": half, "wording": w, "family": family,
                                 "group": simple.wording_group(w), "n": len(items),
                                 "accuracy": round(correct / len(items), 3), "correct": correct})
                row[f"{family}_accuracy"] = round(sum(accs) / len(accs), 3) if accs else ""
                row[f"{family}_under{FEW}"] = few if accs else ""
                row[f"{family}_none"] = none if accs else ""
                row[f"{family}_run"] = len(accs)
            summary.append(row)
    for path, table in ((OUT / "accuracy.csv", rows), (OUT / "summary.csv", summary)):
        with path.open("w", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=list(table[0]))
            writer.writeheader()
            writer.writerows(table)
    write_tex(rows, summary)
    print(f"wrote {OUT.relative_to(ROOT)}/accuracy.csv, summary.csv and {TABLE.relative_to(ROOT)}")


def write_tex(rows: list[dict], summary: list[dict]) -> None:
    acc = {(r["task"], r["half"], r["wording"]): r["accuracy"] for r in rows}
    fmts = [f"{simple.FORMAT_PREFIX}{f}" for f in simple.EXAMPLE_FORMATS]
    lines = ["% Generated by scripts/rebuild_prompt_table.py.",
             r"\begin{tabular}{@{}l" + "r" * 6 + "r" * 6 + "@{}}", r"\toprule",
             r" & \multicolumn{2}{c}{Patched} & \multicolumn{3}{c}{Instruction wordings} & & "
             r"\multicolumn{6}{c}{Example formats} \\",
             r"\cmidrule(lr){2-3}\cmidrule(lr){4-6}\cmidrule(lr){8-13}",
             r"Task & items & \p{ x:} & Yang & P & Q & $<$" + str(FEW) + r" & "
             + " & ".join(f"F{k}" for k in range(1, 7)) + r" \\", r"\midrule"]
    for task in simple.TASKS:
        s = [r for r in summary if r["task"] == task]
        mean = lambda key: sum(float(r[key]) for r in s) / len(s) if all(r[key] != "" for r in s) else None  # noqa: E731
        cells = [task.replace("_", "-"), f"{min(r['patched'] for r in s)}", f"{mean('zero_shot_accuracy'):.2f}"]
        for fam in ("yang", "P", "Q"):
            v = mean(f"{fam}_accuracy")
            cells.append(f"{v:.2f}" if v is not None else "--")
        few = sum(int(r[f"{fam}_under{FEW}"] or 0) for r in s for fam in ("yang", "P", "Q"))
        cells.append(str(few))
        for w in fmts:
            vals = [acc.get((task, h, w)) for h in ("A", "B")]
            cells.append(f"{sum(vals) / 2:.2f}" if None not in vals else "--")
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    TABLE.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
