"""Tables of paper/e8-filter-combos.tex (no GPU).

Sources: results/e8_filters/{fold1,fold2}/{heads,word_lists}.json, set_sizes.csv
(``scripts/e8_sets.py``); results/e8_filters/accuracy_{alpha,crossfit}.csv (``scripts/e8_report.py``);
the patching parts' unpatched rows (items per fold); E4/E7 references as in ``e8_report.refs``;
results/heldout/fold{1,2}/heads.json (E4's FV sets); results/e8_filters/first_run_d10 (the first run,
commit 4d19133: D from E7's 10-word list, Yang's expansion only).

Accuracies: mean of the two folds at the cross-fitted alpha (1 or 2), as in ``e8_report.py``.
Overlap with FV: shared heads per task and fold, and the count expected for a random set of the
same size (|set| x |FV| / 1024), mean of the two folds.

Writes paper/tables/e8_*.tex (tabulars only).

    .venv/bin/python scripts/e8_tables.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))
from e8_report import ALPHAS, crossfit  # noqa: E402
from e8_sets import COMBOS  # noqa: E402
from lth import RESULTS, simple  # noqa: E402

E8 = RESULTS / "e8_filters"
TABLES = ROOT / "paper" / "tables"
HEADER = "% Generated by scripts/e8_tables.py; do not edit.\n"
N_ALL = 1024
REFS = {"E7 raw+F": (RESULTS / "e7_attfilter", "raw_att"), "CC-20": (RESULTS / "heldout", "cc20"),
        "CC": (RESULTS / "heldout", "cc"), "FV-20": (RESULTS / "heldout", "fv20"),
        "FV-$N_t$": (RESULTS / "heldout", "fvNt")}
MAIN = ["D", "B", "T", "DB", "DT", "BT", "DBT"]


def task_tex(t: str) -> str:
    if t.startswith("english-"):
        return "English--" + t.split("-")[1].title()
    return {"next_item": "next-item", "prev_item": "prev-item"}.get(t, t.replace("-", "--"))


def cell(x, bold=False, fmt="{:.2f}") -> str:
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "--"
    s = fmt.format(x) if isinstance(x, (float, np.floating)) else str(x)
    return f"\\textbf{{{s}}}" if bold else s


def tabular(name: str, cols: list[str], rows: list[list[str]], align: str, mid_before: list[int] = ()) -> None:
    lines = [HEADER + f"\\begin{{tabular}}{{{align}}}", "\\toprule", " & ".join(cols) + " \\\\", "\\midrule"]
    for i, r in enumerate(rows):
        if i in mid_before:
            lines.append("\\midrule")
        lines.append(" & ".join(r) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    (TABLES / f"{name}.tex").write_text("\n".join(lines))


def accuracies() -> pd.DataFrame:
    """fold, family, task, set, source, accuracy for the E8 sets and the references."""
    cf = pd.read_csv(E8 / "accuracy_crossfit.csv")
    out = [cf[["fold", "family", "task", "set", "source", "accuracy"]]]
    for name, (root, key) in REFS.items():
        c = pd.read_csv(root / "accuracy_alpha.csv")
        c = c[(c.set == key) & c.alpha.isin(ALPHAS)]
        out.append(crossfit(c).assign(set=name)[["fold", "family", "task", "set", "source", "accuracy"]])
    return pd.concat(out)


def baselines(family: str) -> tuple[pd.Series, pd.DataFrame]:
    rows = []
    for f in (1, 2):
        for p in (E8 / f"fold{f}").glob(f"patching_{family}.part-*.csv"):
            d = pd.read_csv(p)
            rows.append(d[d.source == "none"].assign(fold=f))
    b = pd.concat(rows).drop_duplicates(["fold", "task"])
    return b.groupby("task").accuracy.mean(), b.pivot_table(index="task", columns="fold", values="n_prompts")


def per_task(name: str, acc: pd.DataFrame, family: str, sets: list[str], labels: list[str]) -> None:
    x = acc[acc.family == family]
    task = x[x.source == "task"].groupby(["task", "set"]).accuracy.mean().unstack()
    ctrl = x[x.source == "control"].groupby(["task", "set"]).accuracy.mean().unstack()
    unp, items = baselines(family)
    rows = []
    for t in [*simple.TASKS, "mean"]:
        if t == "mean":
            vals = [task[s].mean() for s in sets]
            r = ["\\textbf{mean}", "", cell(unp.mean())]
        else:
            vals = [task.loc[t, s] if s in task else np.nan for s in sets]
            r = [task_tex(t), f"{int(items.loc[t, 1])}/{int(items.loc[t, 2])}", cell(unp[t])]
        top = np.nanmax(vals)
        r += [cell(v, bold=(v == top)) for v in vals]
        rows.append(r)
    rows.append(["control mean", "", ""] + [cell(ctrl[s].mean()) if s in ctrl else "--" for s in sets])
    tabular(name, ["Task", "items", "unp.", *labels], rows, "l" + "r" * (len(labels) + 2),
            mid_before=[len(simple.TASKS), len(simple.TASKS) + 1])


def all_sets(name: str, acc: pd.DataFrame, family: str) -> None:
    """Every set (rows) x task (columns), task mean, for the appendix."""
    x = acc[(acc.family == family) & (acc.source == "task")]
    task = x.groupby(["set", "task"]).accuracy.mean().unstack().reindex(columns=list(simple.TASKS))
    order = [*COMBOS, *REFS]
    rows = []
    for s in order:
        v = task.loc[s]
        rows.append([s] + [cell(a) for a in v] + [cell(v.mean())])
    short = {"antonym": "ant.", "synonym": "syn.", "singular-plural": "sg--pl", "present-past": "pr--pa",
             "country-capital": "capital", "country-currency": "currency", "landmark-country": "landm.",
             "park-country": "park", "product-company": "product", "next_item": "next", "prev_item": "prev",
             "english-french": "En--Fr", "english-german": "En--De", "english-spanish": "En--Es"}
    tabular(name, ["set", *[short[t] for t in simple.TASKS], "mean"], rows, "l" + "r" * 15,
            mid_before=[5, 15, 25, 30, 31])


def main() -> None:
    TABLES.mkdir(exist_ok=True)
    acc = accuracies()

    # Word lists: fold 1, and how many of its words fold 2 shares.
    W = {f: json.loads((E8 / f"fold{f}" / "word_lists.json").read_text())["tasks"] for f in (1, 2)}
    rows = [[task_tex(t), "\\emph{" + ", ".join(W[1][t]) + "}", str(len(set(W[1][t]) & set(W[2][t])))]
            for t in simple.TASKS]
    tabular("e8_lists", ["Task", "30 most active decoded words (fold 1, most active first)", "fold 2 same"], rows,
            ">{\\raggedright\\arraybackslash}p{2.2cm}>{\\raggedright\\arraybackslash}p{12.4cm}r")

    # Set sizes (mean of the two folds), new and first run.
    sz = pd.concat([pd.read_csv(E8 / f"fold{f}" / "set_sizes.csv") for f in (1, 2)]).groupby("task").mean()
    old = pd.concat([pd.read_csv(E8 / "first_run_d10" / f"fold{f}" / "set_sizes.csv") for f in (1, 2)]).groupby("task").mean()
    cols = ["D", "B", "T", "I", "R", "DB", "DT", "BT", "DBT", "DBTIR"]
    rows = [[task_tex(t), *[cell(sz.loc[t, c], fmt="{:.0f}") for c in cols],
             cell(old.loc[t, "D"], fmt="{:.0f}"), cell(old.loc[t, "DB"], fmt="{:.0f}")] for t in simple.TASKS]
    rows.append(["\\textbf{median}", *[cell(sz[c].median(), fmt="{:.0f}") for c in cols],
                 cell(old.D.median(), fmt="{:.0f}"), cell(old.DB.median(), fmt="{:.0f}")])
    tabular("e8_sizes", ["Task", *cols, "D (1st)", "DB (1st)"], rows, "l" + "r" * (len(cols) + 2),
            mid_before=[len(simple.TASKS)])

    # Overview: every set, mean over tasks.
    s = acc.groupby(["family", "source", "set"]).apply(lambda g: g.groupby("task").accuracy.mean().mean(),
                                                       include_groups=False)
    sizes = pd.concat([pd.read_csv(E8 / f"fold{f}" / "set_sizes.csv") for f in (1, 2)]).groupby("task").mean()
    order = sorted(COMBOS, key=lambda c: -s["simple", "task", c])
    rows = []
    for c in [*order, *REFS]:
        rows.append([c, cell(s["simple", "task", c]), cell(s["simple", "control", c]),
                     cell(s["simple-wrong", "task", c]), cell(s["simple-wrong", "control", c]),
                     cell(sizes[c].median(), fmt="{:.0f}") if c in sizes else "",
                     str(int((sizes[c] > 0).sum())) if c in sizes else ""])
    tabular("e8_overview", ["set", "check 1", "ctrl", "check 2", "ctrl", "heads (median)", "tasks"], rows,
            "lrrrrrr", mid_before=[len(COMBOS)])

    # Per-task tables, main sets against the references.
    labels = [*MAIN, *REFS]
    per_task("e8_check1", acc, "simple", [*MAIN, *REFS], labels)
    per_task("e8_check2", acc, "simple-wrong", [*MAIN, *REFS], labels)
    all_sets("e8_all_check1", acc, "simple")
    all_sets("e8_all_check2", acc, "simple-wrong")

    # First run vs now, every D set.
    o = pd.read_csv(E8 / "first_run_d10" / "accuracy_crossfit.csv")
    n = pd.read_csv(E8 / "accuracy_crossfit.csv")
    m = lambda d, fam, c: d[(d.family == fam) & (d.source == "task") & (d.set == c)].groupby("task").accuracy.mean().mean()  # noqa: E731
    dsets = sorted([c for c in COMBOS if "D" in c], key=lambda c: -m(n, "simple", c))
    rows = [[c, cell(old[c].median(), fmt="{:.0f}"), cell(sz[c].median(), fmt="{:.0f}"),
             cell(m(o, "simple", c)), cell(m(n, "simple", c)), cell(m(o, "simple-wrong", c)), cell(m(n, "simple-wrong", c))]
            for c in dsets]
    tabular("e8_first_run", ["set", "heads, 1st", "heads, now", "check 1, 1st", "check 1, now", "check 2, 1st",
                             "check 2, now"], rows, "lrrrrrr")

    # Filter choice: best set on fold 1 (own best alpha), read on fold 2 (cross-fitted).
    cur = pd.read_csv(E8 / "accuracy_alpha.csv")
    best = cur[(cur.source == "task")].assign(key=lambda d: list(zip(-d.accuracy, d.alpha.abs(), -d.alpha)))
    best = best.sort_values("key").drop_duplicates(["fold", "family", "task", "set"])
    pick = best[(best.fold == 1) & (best.family == "simple")].groupby("set").accuracy.mean().sort_values(ascending=False)
    f2 = acc[(acc.fold == 2) & (acc.family == "simple") & (acc.source == "task")].groupby("set").accuracy.mean()
    rows = [[c, cell(pick[c]), cell(f2[c])] for c in pick.index[:8]]
    tabular("e8_select", ["set", "fold 1, own best $\\alpha$", "fold 2, cross-fitted"], rows, "lrr")

    # List-length check (scripts/e8_list_length.py), mean over tasks and folds.
    ll = pd.read_csv(E8 / "list_length.csv").groupby(["n", "fix"])[["D", "D_fv", "DB", "DB_fv", "generic"]].mean()
    rows = [[str(n), "yes" if fix else "no", cell(r.D, fmt="{:.0f}"), cell(r.D_fv, fmt="{:.1f}"),
             cell(r.D * 20 / N_ALL, fmt="{:.1f}"), cell(r.DB, fmt="{:.0f}"), cell(r.DB_fv, fmt="{:.1f}"),
             cell(r.DB * 20 / N_ALL, fmt="{:.1f}"), f"{r.generic:.0f}/{n}"] for (n, fix), r in ll.iterrows()]
    tabular("e8_listlen", ["words", "case fix", "D", "FV-20 in D", "chance", "DB", "FV-20 in DB", "chance",
                           "generic"], rows, "rlrrrrrrr")

    # Overlap with E4's FV sets.
    def heads(root, f):
        return {t: {k: {tuple(h) for h in hs} for _, k, hs in v["sets"]}
                for t, v in json.loads((root / f"fold{f}" / "heads.json").read_text())["simple"].items()}
    ov = []
    for f in (1, 2):
        e8, e4 = heads(E8, f), heads(RESULTS / "heldout", f)
        for t in simple.TASKS:
            for c in ("D", "T", "DB", "DBT"):
                a = e8[t].get(c, set())
                for fv in ("fv20", "fvNt"):
                    b = e4[t][fv]
                    ov.append(dict(task=t, set=c, fv=fv, shared=len(a & b), chance=len(a) * len(b) / N_ALL))
    ov = pd.DataFrame(ov).groupby(["task", "set", "fv"])[["shared", "chance"]].mean()
    rows = []
    for t in [*simple.TASKS, "mean"]:
        r = [task_tex(t) if t != "mean" else "\\textbf{mean}"]
        for c in ("D", "T", "DB", "DBT"):
            for fv in ("fv20", "fvNt"):
                v = ov.xs((c, fv), level=("set", "fv")).mean() if t == "mean" else ov.loc[(t, c, fv)]
                r.append(f"{v.shared:.1f} ({v.chance:.1f})")
        rows.append(r)
    tabular("e8_overlap", ["Task", "D/FV-20", "D/FV-$N_t$", "T/FV-20", "T/FV-$N_t$", "DB/FV-20", "DB/FV-$N_t$",
                           "DBT/FV-20", "DBT/FV-$N_t$"], rows, "l" + "r" * 8, mid_before=[len(simple.TASKS)])
    fvn = np.mean([len(heads(RESULTS / "heldout", f)[t]["fvNt"]) for f in (1, 2) for t in simple.TASKS])
    print("FV-N_t median-ish size:", fvn)
    print("written:", sorted(p.name for p in TABLES.glob("e8_*.tex")))


if __name__ == "__main__":
    main()
