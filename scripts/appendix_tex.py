"""LaTeX for the proposal's App. C (rule wordings) and App. D (term lists), from materials/.

Writes ``appendix-wordings.tex`` and ``appendix-terms.tex`` next to the proposal, for the
original rules prompts of the levels in the study (``lth.fu.STUDY_LEVELS``). They are
meant to be ``\\input`` in place of the two placeholders of ``appendix-prompts.tex``; the
wordings use the proposal's ``promptbox`` environment.

    .venv/bin/python scripts/appendix_tex.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from lth import MATERIALS, ROOT, fu  # noqa: E402

TASK_NAMES = {"set_game": "Set Game", "operator_func": "Operator Function", "tapatan": "Tapatan",
              "noun_class_agreement": "Noun Class Agreement",
              "lexical_category_inference": "Lexical Category Inference"}


def main() -> None:
    wordings = json.loads((MATERIALS / "complex" / "wordings.json").read_text())
    terms = json.loads((MATERIALS / "complex" / "terms.json").read_text())
    originals = list(dict.fromkeys(fu.TASK_LEVELS[k].original for k in fu.STUDY_LEVELS))

    out = ["% Generated by scripts/appendix_tex.py from materials/complex/wordings.json."]
    for key in originals:
        task = TASK_NAMES[key.split("/")[0]]
        out += ["", f"\\subsection*{{{task}, easy level}}"]
        for i, text in enumerate(wordings[key], 1):
            out += ["", f"\\paragraph{{Wording {i}.}}", "\\begin{promptbox}", text, "\\end{promptbox}"]
    (ROOT / "appendix-wordings.tex").write_text("\n".join(out) + "\n")

    out = ["% Generated by scripts/appendix_tex.py from materials/complex/terms.json.",
           "\\begin{footnotesize}", "\\begin{tabular}{@{}lp{0.7\\textwidth}@{}}", "\\toprule",
           "Task (easy level) & Terms \\\\", "\\midrule"]
    for key in originals:
        task = TASK_NAMES[key.split("/")[0]]
        out.append(f"{task} & {', '.join(terms[key])} \\\\[2pt]")
    out += ["\\bottomrule", "\\end{tabular}", "\\end{footnotesize}"]
    (ROOT / "appendix-terms.tex").write_text("\n".join(out) + "\n")
    print("wrote appendix-wordings.tex, appendix-terms.tex for", ", ".join(originals))


if __name__ == "__main__":
    main()
